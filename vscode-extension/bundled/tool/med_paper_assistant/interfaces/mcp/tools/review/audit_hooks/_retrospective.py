"""write_pipeline_retrospective tool."""

from datetime import datetime
from pathlib import Path
from typing import Optional

from mcp.server.mcpserver import Context

from med_paper_assistant.infrastructure.persistence.workspace_state_manager import (
    get_workspace_state_manager,
)

from ..._shared import (
    log_tool_call,
    log_tool_error,
    log_tool_result,
    report_tool_progress,
)
from .._tool_doc import nested_tool_doc
from ._common import _coerce_project_info, resolve_manuscript_project


def _write_pipeline_retrospective_artifact(
    *,
    project_dir: Path,
    slug: str,
    summary: str = "",
    d7_retrospective: str = "",
    d8_retrospective: str = "",
) -> Path:
    """Create the Phase 10 pipeline-run artifact with required D7/D8 headings."""
    audit_dir = project_dir / ".audit"
    audit_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d-%H%M")
    path = audit_dir / f"pipeline-run-{ts}.md"
    if path.exists():
        path = audit_dir / f"pipeline-run-{datetime.now().strftime('%Y%m%d-%H%M%S')}.md"

    state = get_workspace_state_manager().get_state()
    pipeline_state = state.get("pipeline_state", {})
    lines = [
        "---",
        "schema: mdpaper.pipeline_run.v1",
        f"project: {slug}",
        f"generated_at: {datetime.now().isoformat()}",
        "---",
        "",
        "# Pipeline Run Retrospective",
        "",
        "## Summary",
        "",
        summary.strip() or "Pipeline retrospective generated by MCP tooling.",
        "",
        "## Gate state snapshot",
        "",
        f"- Current phase: {pipeline_state.get('current_phase')}",
        f"- Last gate result: {pipeline_state.get('last_gate_result')}",
        f"- Next required action: {pipeline_state.get('next_required_action')}",
        "",
        "## D7 retrospective: Review Retrospective",
        "",
        d7_retrospective.strip()
        or "Review loop completed or is ready for final validation. See review-report-N.md and author-response-N.md artifacts.",
        "",
        "## D8 retrospective: EQUATOR Retrospective",
        "",
        d8_retrospective.strip()
        or "EQUATOR/reporting guideline compliance artifacts reviewed. See equator-compliance-N.md or equator-na-N.md.",
        "",
    ]
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


@nested_tool_doc
async def write_pipeline_retrospective(
    summary: str = "",
    d7_retrospective: str = "",
    d8_retrospective: str = "",
    project: Optional[str] = None,
    ctx: Context | None = None,
) -> str:
    """
    Write the Phase 10 `.audit/pipeline-run-*.md` retrospective artifact.

    This removes the previous agent friction where the gate required a
    timestamped filename and exact D7/D8 headings but provided no writer.
    """
    log_tool_call("write_pipeline_retrospective", {"project": project})
    try:
        project_info, workflow_error = resolve_manuscript_project(project)
        if workflow_error:
            return workflow_error
        project_info = _coerce_project_info(project_info)
        await report_tool_progress(ctx, 0, 2, "Resolving project context", end=95)
        slug = project_info["slug"]
        project_dir = Path(project_info["project_path"])
        path = _write_pipeline_retrospective_artifact(
            project_dir=project_dir,
            slug=slug,
            summary=summary,
            d7_retrospective=d7_retrospective,
            d8_retrospective=d8_retrospective,
        )
        await report_tool_progress(ctx, 2, 2, "Pipeline retrospective written")
        rel = path.relative_to(project_dir).as_posix()
        log_tool_result("write_pipeline_retrospective", rel)
        return (
            "status: ok\n"
            "action: pipeline_retrospective\n"
            f"file: {rel}\n"
            "required_headings: D7,D8\n"
            'next: pipeline_action(action="validate_phase", phase=10, response_format="json", compact=true)'
        )
    except Exception as e:
        log_tool_error("write_pipeline_retrospective", e)
        return f"❌ Error writing pipeline retrospective: {e}"
